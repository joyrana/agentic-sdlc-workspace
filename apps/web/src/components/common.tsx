const STRATEGY_TEXT: Record<
  string,
  { label: string; tip: string; color: "brand" | "warning" | "informative" | "severe" }
> = {
  llm: {
    label: "Model",
    tip: "Produced by a language model and validated against the skill's schema",
    color: "brand",
  },
  heuristic: {
    label: "Rule-based",
    tip: "Produced by deterministic rules, not a language model. No model inference is configured.",
    color: "informative",
  },
  scripted: {
    label: "Scripted fixture",
    tip: "Replayed from a fixture for a sample repository. Not generated by a model.",
    color: "warning",
  },
  mock: {
    label: "Mock model",
    tip: "Deterministic mock provider used for testing. Not real inference.",
    color: "severe",
  },
  human: { label: "Human", tip: "Written or edited by a person", color: "informative" },
};

/** Shows how an artifact was produced. Required wherever generated output is displayed. */
export function StrategyBadge({ strategy, model }: { strategy: string; model?: string | null }) {
  const meta = STRATEGY_TEXT[strategy] ?? { label: strategy, tip: strategy, color: "informative" as const };
  return (
    <Tooltip content={model ? `${meta.tip} (${model})` : meta.tip} relationship="description">
      <Badge appearance="outline" color={meta.color} size="small">
        {meta.label}
      </Badge>
    </Tooltip>
  );
}

