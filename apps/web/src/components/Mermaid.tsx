import { Text, makeStyles, tokens } from "@fluentui/react-components";
import { useEffect, useId, useState } from "react";

const useStyles = makeStyles({
  frame: {
    border: `1px solid ${tokens.colorNeutralStroke2}`,
    borderRadius: tokens.borderRadiusLarge,
    padding: tokens.spacingHorizontalL,
    backgroundColor: tokens.colorNeutralBackground1,
    overflowX: "auto",
  },
  code: { fontFamily: tokens.fontFamilyMonospace, fontSize: tokens.fontSizeBase200, whiteSpace: "pre" },
});

/** Renders Mermaid source. The library is loaded on demand; strict security level (no click handlers or HTML). */
export function Mermaid({ source, label }: { source: string; label: string }) {
  const s = useStyles();
  const id = useId().replace(/[^a-zA-Z0-9]/g, "");
  const [svg, setSvg] = useState<string | null>(null);
  const [failed, setFailed] = useState(false);
  useEffect(() => {
    let cancelled = false;
    void (async () => {
      try {
        const mermaid = (await import("mermaid")).default;
        const dark = window.matchMedia("(prefers-color-scheme: dark)").matches;
        mermaid.initialize({ startOnLoad: false, securityLevel: "strict", theme: dark ? "dark" : "neutral" });
        const { svg: out } = await mermaid.render(`m${id}`, source);
        if (!cancelled) setSvg(out);
      } catch {
        if (!cancelled) setFailed(true);
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [source, id]);
  if (failed || !svg) {
    return (
      <div className={s.frame} role="img" aria-label={label}>
        {failed && <Text size={200}>The diagram could not be rendered; source shown instead.</Text>}
        <div className={s.code}>{source}</div>
      </div>
    );
  }
  // Mermaid output is generated by the library in strict mode from server-provided text.
  return <div className={s.frame} role="img" aria-label={label} dangerouslySetInnerHTML={{ __html: svg }} />;
}
